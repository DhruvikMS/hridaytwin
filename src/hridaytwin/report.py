"""Generate docs/RESULTS.md and docs/figures/*.png from model/*.json.

Nothing in RESULTS.md is typed by hand; re-running the pipeline regenerates it.
"""
from __future__ import annotations

import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from . import config  # noqa: E402

INK, ACCENT, TWIN, CRIT, MUTED = "#16262B", "#0E6A73", "#6A55C9", "#C23E2A", "#8A979B"
NAMES = {"ehr_only": "EHR only", "stream_only": "Wearable + home devices only",
         "fused": "**Fused EHR + stream (deployed)**", "fused_plus_twin_state": "Fused + twin-state features",
         "fused_logistic": "Fused, logistic regression", "clinical_rules": "Threshold rules (no model)"}
EVN = {"severe_hypoglycaemia": "Severe hypoglycaemia", "hyperglycaemic_crisis": "Hyperglycaemic crisis",
       "hypertensive_emergency": "Hypertensive emergency", "acute_cv_event": "Acute CV event"}


def _style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.spines["left"].set_color(MUTED)
    ax.spines["bottom"].set_color(MUTED)
    ax.tick_params(colors=INK, labelsize=9)
    ax.grid(axis="y", color="#DCE3DF", lw=0.8)
    ax.set_axisbelow(True)


def p_fmt(p):
    return "< 0.001" if p <= 0.001 else f"{p:.3f}"


def figures(m, tv):
    out = config.DOCS_DIR / "figures"
    out.mkdir(parents=True, exist_ok=True)
    # 1. variants
    order = ["clinical_rules", "stream_only", "ehr_only", "fused_plus_twin_state", "fused_logistic", "fused"]
    labels = [NAMES[k].replace("**", "") for k in order]
    vals = [m["variants"][k]["auroc"] for k in order]
    fig, ax = plt.subplots(figsize=(7.2, 3.2))
    cols = [ACCENT if k == "fused" else MUTED for k in order]
    ax.barh(labels, vals, color=cols, height=0.6)
    for y, v in enumerate(vals):
        ax.text(v + 0.003, y, f"{v:.3f}", va="center", fontsize=9, color=INK)
    ax.set_xlim(0.5, max(vals) + 0.05)
    ax.set_xlabel("AUROC, 14-day composite event (5-fold patient-grouped CV)", fontsize=9, color=INK)
    _style(ax); ax.grid(axis="x", color="#DCE3DF", lw=0.8); ax.grid(axis="y", visible=False)
    fig.tight_layout(); fig.savefig(out / "model_comparison.png", dpi=160); plt.close(fig)

    # 2. twin convergence
    fig, ax = plt.subplots(figsize=(6.4, 3.2))
    for key, c, lab in [("glucose", ACCENT, "Glucose drug response"), ("blood_pressure", TWIN, "BP drug response")]:
        cp = tv[key]["checkpoints"]
        ax.plot([0] + [r["week"] for r in cp], [0] + [r["corr_with_truth"] for r in cp], "-o", color=c, lw=2, ms=4, label=lab)
    ax.set_xlabel("Weeks of wearable / home-device data", fontsize=9, color=INK)
    ax.set_ylabel("Correlation with hidden truth", fontsize=9, color=INK)
    ax.set_ylim(-0.02, 1); ax.legend(frameon=False, fontsize=9)
    ax.text(1.2, 0.06, "EHR prior = 0 (population average)", fontsize=8, color=MUTED)
    _style(ax); fig.tight_layout(); fig.savefig(out / "twin_convergence.png", dpi=160); plt.close(fig)

    # 3. reliability
    rel = m["reliability"]
    fig, ax = plt.subplots(figsize=(3.8, 3.6))
    mx = max(max(r["mean_pred"] for r in rel), max(r["observed"] for r in rel)) * 1.1
    ax.plot([0, mx], [0, mx], "--", color=MUTED, lw=1)
    ax.plot([r["mean_pred"] for r in rel], [r["observed"] for r in rel], "-o", color=ACCENT, lw=2, ms=4)
    ax.set_xlabel("Predicted 14-day risk (decile mean)", fontsize=9, color=INK)
    ax.set_ylabel("Observed event rate", fontsize=9, color=INK)
    _style(ax); fig.tight_layout(); fig.savefig(out / "calibration.png", dpi=160); plt.close(fig)


def main():
    m = json.loads((config.MODEL_DIR / "metrics.json").read_text())
    tv = json.loads((config.MODEL_DIR / "twin_validation.json").read_text())
    ss_path = config.MODEL_DIR / "seed_robustness.json"
    ss = json.loads(ss_path.read_text()) if ss_path.exists() else None
    figures(m, tv)
    V, Dl, op, opr = m["variants"], m["paired_deltas"], m["operating_point"], m["operating_point_rules"]
    L = []
    w = L.append
    w("# Results\n")
    w("> **Generated file.** Produced by `python -m hridaytwin.report` from `model/metrics.json`, "
      "`model/twin_validation.json` and `model/seed_robustness.json`. Do not edit by hand.\n")
    w("> All numbers come from a **synthetic** cohort generated by this repository. They show that the "
      "pipeline works end to end and where each data source adds signal. They are not evidence of clinical performance.\n")
    c = m["config"]
    w(f"Cohort: **{m['n_patients']} patients x {c['days']} days**, {m['n_rows']:,} weekly prediction points, "
      f"event base rate **{m['positive_rate']*100:.1f}%** per 14-day window. Seed {c['seed']}. "
      f"Full pipeline runtime {m['runtime_seconds']:.0f} s on a laptop CPU.\n")

    w("## 1. Does the twin learn the individual patient?\n")
    w("The EHR prior assumes every patient responds to their medicines like the published average, so its "
      "correlation with each patient's true response is zero by construction. The twin updates that prior from "
      "the daily stream (pill-box adherence, CGM/glucometer, home BP, steps, resting HR).\n")
    w("| Weeks of data | Glucose: corr. with truth | Glucose: mean abs. error | BP: corr. with truth | BP: mean abs. error |")
    w("|---:|---:|---:|---:|---:|")
    w(f"| 0 (EHR prior) | 0.00 | {tv['glucose']['prior_mae_multiplier']:.3f} | 0.00 | {tv['blood_pressure']['prior_mae_multiplier']:.3f} |")
    for g, b in zip(tv["glucose"]["checkpoints"], tv["blood_pressure"]["checkpoints"]):
        w(f"| {g['week']:.0f} | {g['corr_with_truth']:.3f} | {g['mae_multiplier']:.3f} | {b['corr_with_truth']:.3f} | {b['mae_multiplier']:.3f} |")
    w(f"\nGlucose: {tv['glucose']['n_patients']} patients on glucose-lowering drugs; BP: {tv['blood_pressure']['n_patients']} on BP-lowering drugs; "
      "patients whose treatment changed after an admission are excluded because their true response changed mid-stream. "
      "Error is in units of the response multiplier (1.0 = average responder).\n")
    pc = tv["predictive_calibration"]
    w(f"Predictive calibration of the twin's daily expectations: glucose z-score mean {pc['glucose_z_mean']}, sd {pc['glucose_z_sd']}, "
      f"{pc['glucose_within_2sd']*100:.0f}% of readings within 2 sd; home SBP z mean {pc['sbp_z_mean']}, sd {pc['sbp_z_sd']}, "
      f"{pc['sbp_within_2sd']*100:.0f}% within 2 sd. A calibrated twin gives mean 0, sd 1, about 95% within 2 sd.\n")
    w("![Twin convergence](figures/twin_convergence.png)\n")
    g_last, g_prior = tv["glucose"]["checkpoints"][-1]["mae_multiplier"], tv["glucose"]["prior_mae_multiplier"]
    w(f"**Reading this table.** The twin learns to *rank* patients by how strongly their medicines work for them (correlation rises from 0 to "
      f"{tv['glucose']['checkpoints'][-1]['corr_with_truth']:.2f} for glucose), which is what plan selection needs. Absolute error falls only modestly "
      f"({g_prior:.3f} to {g_last:.3f}) because the filter shrinks estimates toward the prior until the data are strong. It learns because pill-box lapses act as natural on/off experiments.\n")
    w("**Limit.** "
      "It does **not** reliably recover each patient's step sensitivity (correlation with truth stayed near zero in development), "
      "so the activity arm of the what-if simulator relies mostly on the literature prior.\n")

    w("## 2. Does fusing wearables with the EHR predict adverse events better?\n")
    w("Task: at a weekly check-in, predict any adverse cardiometabolic event (severe hypoglycaemia, hyperglycaemic crisis, "
      "hypertensive emergency, acute CV event) in the next 14 days. 5-fold GroupKFold by patient: no patient is ever in both train and test.\n")
    w("| Model | AUROC | AUPRC | Brier | ECE |")
    w("|---|---:|---:|---:|---:|")
    for k in ["fused", "fused_logistic", "fused_plus_twin_state", "ehr_only", "stream_only", "clinical_rules"]:
        v = V[k]
        w(f"| {NAMES[k]} | {v['auroc']:.3f} | {v['auprc']:.3f} | {v.get('brier', float('nan')):.4f} | {v.get('ece', float('nan')):.4f} |".replace("nan", "–"))
    w("\n![Model comparison](figures/model_comparison.png)\n")
    w("Paired comparisons on identical folds, two-sided p-values from a 1,000-resample **patient-level** cluster bootstrap:\n")
    w("| Comparison | Delta AUROC | 95% CI | p |")
    w("|---|---:|---|---:|")
    for k, v in Dl.items():
        w(f"| {k.replace('_', ' ')} | {v['delta']:+.4f} | [{v['ci95'][0]:+.4f}, {v['ci95'][1]:+.4f}] | {p_fmt(v['p_value'])} |")
    th = m["temporal_holdout"]
    w(f"\n**Temporal + patient hold-out** (train on weeks before day {config.TEMPORAL_SPLIT_DAY - config.HORIZON_DAYS}, test on day "
      f"{config.TEMPORAL_SPLIT_DAY}+ of unseen patients, n = {th['n_test']:,}): fused {th['fused_auroc']:.3f} vs EHR-only {th['ehr_only_auroc']:.3f}. "
      "The gain is smaller here than under cross-validation; we report both.\n")
    w(f"**Label-permutation control:** {m['controls']['label_permutation_auroc']:.3f} (must be about 0.50; it is, so the pipeline does not leak labels).\n")

    w("### By event type\n")
    w("| Event | Positive windows | Fused AUROC | EHR-only AUROC | Delta (95% CI) | p |")
    w("|---|---:|---:|---:|---|---:|")
    for t, v in m["event_types"].items():
        d = v["delta_vs_ehr"]
        w(f"| {EVN[t]} | {v['positives']} | {v['fused_auroc']:.3f} | {v['ehr_only_auroc']:.3f} | {d['delta']:+.3f} [{d['ci95'][0]:+.3f}, {d['ci95'][1]:+.3f}] | {p_fmt(d['p_value'])} |")
    w("\nThe stream adds most where physiology moves fast and is measured directly: **severe hypoglycaemia** (CGM lows, fasting days, missed meals). "
      "Acute CV events stay dominated by baseline risk in the clinic record; the stream does not improve them here.\n")

    w("### Timing: can it tell *which week* is dangerous for the same patient?\n")
    T = m["timing_pre_first_event"]
    w("Mean within-patient AUROC over the weeks **before each patient's first event**. The EHR is constant across those weeks, so it scores exactly 0.50; "
      "anything above that is the stream telling the clinician *when* to act.\n")
    w("| Model | Within-patient AUROC | Patients |")
    w("|---|---:|---:|")
    for k, v in T.items():
        w(f"| {NAMES[k]} | {v['mean_within_patient_auroc']:.3f} | {v['n_patients']} |")
    w("\nThis signal is real but modest. Events here are short-lived hazard spikes (an infection, a fasting day), and a weekly 14-day "
      "forecast catches only part of them. Daily scoring and a shorter horizon are the obvious next experiment.\n")

    w("### Calibration and operating point\n")
    w(f"Alert budget **{op['alert_budget_per_patient_week']*100:.0f} alerts per 100 patient-weeks** (threshold {op['threshold']*100:.1f}% risk):\n")
    w("| | Fused model | Threshold rules |")
    w("|---|---:|---:|")
    for k, lab in [("sensitivity", "Sensitivity"), ("ppv", "Positive predictive value"), ("lift_over_base_rate", "Lift over base rate"), ("median_lead_time_days", "Median warning before event (days)")]:
        a, b = op[k], opr[k]
        fmt = (lambda x: f"{x*100:.1f}%") if k in ("sensitivity", "ppv") else (lambda x: f"{x}")
        w(f"| {lab} | {fmt(a)} | {fmt(b)} |")
    w("\n![Calibration](figures/calibration.png)\n")

    if ss:
        w("## 3. Seed robustness\n")
        w("The whole pipeline (new cohort, new twin, new models) re-run under different generator seeds:\n")
        w("| Seed | Rows | Base rate | EHR-only | Fused | Fused + twin state | Fused - EHR | Timing (fused) |")
        w("|---:|---:|---:|---:|---:|---:|---:|---:|")
        for r in ss["per_seed"]:
            w(f"| {r['seed']} | {r['n_rows']:,} | {r['positive_rate']*100:.1f}% | {r['ehr_only_auroc']:.3f} | {r['fused_auroc']:.3f} | {r['fused_plus_twin_state_auroc']:.3f} | {r['fused_minus_ehr']:+.3f} | {r['timing_fused']:.3f} |")
        s = ss["summary"]
        w(f"\nFused minus EHR: **{s['fused_minus_ehr']['mean']:+.3f} +/- {s['fused_minus_ehr']['sd']:.3f}**; fused beats EHR-only in {s['fused_beats_ehr_in']}.\n")

    w("## 4. Negative findings and caveats\n")
    w("- **Twin-state features do not help the risk model.** Adding the twin's coefficients and surprise scores to the fused model lowered AUROC "
      f"({Dl['fused_vs_fused_plus_twin_state']['delta']:+.3f} in favour of leaving them out). The deployed risk model therefore uses EHR + stream windows, "
      "and the twin's job is generative: learning the patient and simulating care plans. We chose this after seeing the result; it is a post-hoc decision and is labelled as one.\n")
    w("- **Model settings were chosen on the same cross-validation** (two regularisation settings compared). The temporal hold-out and seed sweep are the less optimistic checks.\n")
    w("- **Synthetic data.** The generator is mechanistic and literature-anchored, but its signal sits where we put it. Real validation needs paired EHR + "
      "wearable data from Indian patients (see `docs/VALIDATION_PLAN.md`).\n")
    w("- **What-if effects of new drugs** are published averages scaled by the patient's learned response; they are not causal estimates from this patient's data.\n")
    (config.DOCS_DIR / "RESULTS.md").write_text("\n".join(L))
    print("wrote docs/RESULTS.md")


if __name__ == "__main__":
    main()
